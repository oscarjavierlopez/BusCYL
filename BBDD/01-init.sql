CREATE SCHEMA IF NOT EXISTS buscyl;

CREATE TABLE IF NOT EXISTS buscyl.roles (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre  VARCHAR(50) NOT NULL,
    CONSTRAINT pk_roles        PRIMARY KEY (id),
    CONSTRAINT ck_roles_nombre CHECK (nombre IN ('administrador', 'coordinador empresa', 'conductor', 'pasajero'))
);

CREATE TABLE IF NOT EXISTS buscyl.provincias (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre  VARCHAR(100) NOT NULL,
    CONSTRAINT pk_provincias PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS buscyl.localidades (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre        VARCHAR(100) NOT NULL,
    id_provincia  BIGINT NOT NULL,
    CONSTRAINT pk_localidades      PRIMARY KEY (id),
    CONSTRAINT fk_localidades_provincia FOREIGN KEY (id_provincia) REFERENCES buscyl.provincias (id)
);

CREATE TABLE IF NOT EXISTS buscyl.empresas (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR(150) NOT NULL,
    razon_social   VARCHAR(150) NOT NULL,
    cif            VARCHAR(9)   NOT NULL,
    telefono       VARCHAR(15)  NOT NULL,
    email          VARCHAR(150) NOT NULL,
    direccion      VARCHAR(255) NOT NULL,
    id_localidad   BIGINT      NOT NULL,
    CONSTRAINT pk_empresas             PRIMARY KEY (id),
    CONSTRAINT uq_empresas_razon_social UNIQUE (razon_social),
    CONSTRAINT uq_empresas_cif          UNIQUE (cif),
    CONSTRAINT uq_empresas_telefono     UNIQUE (telefono),
    CONSTRAINT uq_empresas_email        UNIQUE (email),
    CONSTRAINT fk_empresas_localidad    FOREIGN KEY (id_localidad) REFERENCES buscyl.localidades (id)
);

CREATE TABLE IF NOT EXISTS buscyl.usuarios (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email             VARCHAR(150) NOT NULL,
    id_rol            BIGINT      NOT NULL,
    nombre            VARCHAR(100) NOT NULL,
    apellidos         VARCHAR(150) NOT NULL,
    dni               VARCHAR(9)   NOT NULL,
    telefono          VARCHAR(15)  NOT NULL,
    contrasena        VARCHAR(255) DEFAULT NULL,
    fecha_nacimiento  DATE        NOT NULL,
    fecha_registro    DATE        NOT NULL,
    id_empresa        BIGINT      NULL,
    activo            BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_usuarios         PRIMARY KEY (id),
    CONSTRAINT uq_usuarios_email    UNIQUE (email),
    CONSTRAINT uq_usuarios_dni      UNIQUE (dni),
    CONSTRAINT uq_usuarios_telefono UNIQUE (telefono),
    CONSTRAINT fk_usuarios_rol      FOREIGN KEY (id_rol) REFERENCES buscyl.roles (id),
    CONSTRAINT fk_usuarios_empresa  FOREIGN KEY (id_empresa) REFERENCES buscyl.empresas (id)
);

CREATE TABLE IF NOT EXISTS buscyl.avisos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario  BIGINT       NOT NULL,
    motivo      VARCHAR(255) NOT NULL,
    fecha_aviso DATE         NOT NULL,
    CONSTRAINT pk_avisos         PRIMARY KEY (id),
    CONSTRAINT fk_avisos_usuario FOREIGN KEY (id_usuario) REFERENCES buscyl.usuarios (id)
);

CREATE TABLE IF NOT EXISTS buscyl.invitaciones (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario        BIGINT       NOT NULL,
    token             VARCHAR(255) NOT NULL,
    fecha_creacion    DATE         NOT NULL,
    fecha_expiracion  DATE         NOT NULL,
    fecha_uso         DATE         NULL,
    CONSTRAINT pk_invitaciones         PRIMARY KEY (id),
    CONSTRAINT fk_invitaciones_usuario FOREIGN KEY (id_usuario) REFERENCES buscyl.usuarios (id)
);

CREATE TABLE IF NOT EXISTS buscyl.autobuses (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    matricula         VARCHAR(10) NOT NULL,
    id_empresa        BIGINT      NOT NULL,
    numero_bastidor   VARCHAR(17) NOT NULL,
    numero_flota      VARCHAR(20) NOT NULL,
    CONSTRAINT pk_autobuses              PRIMARY KEY (id),
    CONSTRAINT uq_autobuses_matricula     UNIQUE (matricula),
    CONSTRAINT uq_autobuses_bastidor      UNIQUE (numero_bastidor),
    CONSTRAINT uq_autobuses_flota         UNIQUE (numero_flota),
    CONSTRAINT fk_autobuses_empresa       FOREIGN KEY (id_empresa) REFERENCES buscyl.empresas (id)
);

CREATE TABLE IF NOT EXISTS buscyl.asientos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_autobus  BIGINT       NOT NULL,
    numero      INTEGER      NOT NULL,
    tipo        VARCHAR(10)  NOT NULL DEFAULT 'normal',
    activo      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_asientos         PRIMARY KEY (id),
    CONSTRAINT ck_asientos_tipo    CHECK (tipo IN ('normal', 'adaptado')),
    CONSTRAINT fk_asientos_autobus FOREIGN KEY (id_autobus) REFERENCES buscyl.autobuses (id)
);

CREATE TABLE IF NOT EXISTS buscyl.viajes (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_origen     BIGINT NOT NULL,
    id_destino    BIGINT NOT NULL,
    id_autobus    BIGINT NOT NULL,
    id_conductor  BIGINT NOT NULL,
    fecha_viaje   DATE   NOT NULL,
    hora_salida   TIME   NOT NULL,
    hora_llegada  TIME   NOT NULL,
    CONSTRAINT pk_viajes          PRIMARY KEY (id),
    CONSTRAINT fk_viajes_origen   FOREIGN KEY (id_origen)    REFERENCES buscyl.localidades (id),
    CONSTRAINT fk_viajes_destino  FOREIGN KEY (id_destino)   REFERENCES buscyl.localidades (id),
    CONSTRAINT fk_viajes_autobus  FOREIGN KEY (id_autobus)   REFERENCES buscyl.autobuses (id),
    CONSTRAINT fk_viajes_conductor FOREIGN KEY (id_conductor) REFERENCES buscyl.usuarios (id)
);

CREATE TABLE IF NOT EXISTS buscyl.paradas (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_viaje      BIGINT       NOT NULL,
    id_localidad  BIGINT       NOT NULL,
    hora_llegada  TIME         NOT NULL,
    hora_salida   TIME         NOT NULL,
    direccion     VARCHAR(255) NOT NULL,
    orden         INTEGER      NOT NULL,
    CONSTRAINT pk_paradas           PRIMARY KEY (id),
    CONSTRAINT fk_paradas_viaje     FOREIGN KEY (id_viaje)     REFERENCES buscyl.viajes (id),
    CONSTRAINT fk_paradas_localidad FOREIGN KEY (id_localidad) REFERENCES buscyl.localidades (id)
);

CREATE TABLE IF NOT EXISTS buscyl.reservas (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_pasajero         BIGINT       NOT NULL,
    id_viaje            BIGINT       NOT NULL,
    id_asiento          BIGINT       NOT NULL,
    id_parada_origen    BIGINT       NOT NULL,
    id_parada_destino   BIGINT       NOT NULL,
    estado              VARCHAR(10)  NOT NULL DEFAULT 'confirmada',
    fecha_reserva       DATE         NOT NULL,
    fecha_cancelacion   DATE         NULL,
    codigo_qr           VARCHAR(255) NOT NULL,
    CONSTRAINT pk_reservas               PRIMARY KEY (id),
    CONSTRAINT ck_reservas_estado        CHECK (estado IN ('confirmada', 'cancelada')),
    CONSTRAINT fk_reservas_pasajero      FOREIGN KEY (id_pasajero)       REFERENCES buscyl.usuarios (id),
    CONSTRAINT fk_reservas_viaje         FOREIGN KEY (id_viaje)          REFERENCES buscyl.viajes (id),
    CONSTRAINT fk_reservas_asiento       FOREIGN KEY (id_asiento)        REFERENCES buscyl.asientos (id),
    CONSTRAINT fk_reservas_parada_origen FOREIGN KEY (id_parada_origen)  REFERENCES buscyl.paradas (id),
    CONSTRAINT fk_reservas_parada_destino FOREIGN KEY (id_parada_destino) REFERENCES buscyl.paradas (id)
);

CREATE TABLE IF NOT EXISTS buscyl.validaciones_reservas (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_reserva        BIGINT NOT NULL,
    id_conductor      BIGINT NOT NULL,
    id_pasajero       BIGINT NOT NULL,
    fecha_validacion  DATE   NOT NULL,
    CONSTRAINT pk_validaciones_reservas           PRIMARY KEY (id),
    CONSTRAINT fk_validaciones_reservas_reserva   FOREIGN KEY (id_reserva)   REFERENCES buscyl.reservas (id),
    CONSTRAINT fk_validaciones_reservas_conductor FOREIGN KEY (id_conductor) REFERENCES buscyl.usuarios (id),
    CONSTRAINT fk_validaciones_reservas_pasajero  FOREIGN KEY (id_pasajero)  REFERENCES buscyl.usuarios (id)
);
